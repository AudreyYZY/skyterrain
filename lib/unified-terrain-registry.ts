// ============================================================
// 辅助函数：从 category 字符串归一化
// ============================================================
function normalizeCategory(cat: string): TerrainCategory {
  const map: Record<string, TerrainCategory> = {
    "mountain_range": "mountain_system",
    "mountain_system": "mountain_system",
    "basin": "basin",
    "desert": "desert",
    "plateau": "plateau",
    "lake": "lake",
    "peak": "peak",
    "valley": "valley",
    "river": "river",
    "canyon": "canyon",
    "plain": "plain",
    "oasis": "desert",
    "city": "peak",  // fallback to peak for city-like categories
  };
  return map[cat] ?? "plateau";
}

// ============================================================
// 辅助函数：生成小圆圈 polygon (用于无 GIS 数据的地形)
// 半径基于 elevation 动态计算
// ============================================================
function generateCirclePolygon(
  lon: number, lat: number, elevation: number
): [number, number][] {
  // 基础半径 0.3 度，高程越高半径越大
  const radius = Math.max(0.2, 0.15 + elevation / 30000);
  const points = 32;
  const result: [number, number][] = [];
  for (let i = 0; i <= points; i++) {
    const angle = (i / points) * 2 * Math.PI;
    const dLon = (radius * Math.cos(angle)) / Math.cos(lat * Math.PI / 180);
    const dLat = radius * Math.sin(angle);
    result.push([+(lon + dLon).toFixed(4), +(lat + dLat).toFixed(4)]);
  }
  return result;
}

